from router import Router


class LSrouter(Router):
    """Link state routing protocol implementation.

    Add your own class fields and initialization code (e.g. to create forwarding table
    data structures). See the `Router` base class for docstrings of the methods to
    override.
    """

    def __init__(self, addr, heartbeat_time):
        Router.__init__(self, addr)  # Initialize base class - DO NOT REMOVE
        self.heartbeat_time = heartbeat_time
        self.last_time = 0
        # TODO
        #   add your own class fields and initialization code here
        self.neighbors = {}
        self.sequence_number = 0
        self.link_state_db = {self.addr: {"seq": 0, "links": {}}}
        self.forwarding_table = {}

    def handle_packet(self, port, packet):
        """Process incoming packet."""
        # TODO
        if packet.is_traceroute:
            # Hint: this is a normal data packet
            # If the forwarding table contains packet.dst_addr
            #   send packet based on forwarding table, e.g., self.send(port, packet)
            if packet.dst_addr in self.forwarding_table:
                next_port = self.forwarding_table[packet.dst_addr]
                self.send(next_port, packet)
        else:
            # Hint: this is a routing packet generated by your routing protocol
            # If the sequence number is higher and the received link state is different
            #   update the local copy of the link state
            #   update the forwarding table
            #   broadcast the packet to other neighbors
            import json
            from packet import Packet

            if not packet.is_routing or port not in self.neighbors:
                return

            try:
                lsp = json.loads(packet.content)
                origin = lsp["origin"]
                seq = lsp["seq"]
                links = lsp["links"]
            except (TypeError, ValueError, KeyError):
                return

            if (
                not isinstance(origin, str)
                or not isinstance(seq, int)
                or seq < 0
                or not isinstance(links, dict)
            ):
                return

            previous = self.link_state_db.get(origin)

            if previous is not None and seq <= previous["seq"]:
                return

            self.link_state_db[origin] = {
                "seq": seq,
                "links": links.copy()
            }

            self._recompute_routes()

            for out_port, (endpoint, cost) in self.neighbors.items():
                if out_port == port:
                    continue

                flooded_packet = Packet(
                    Packet.ROUTING,
                    self.addr,
                    endpoint,
                    packet.content
                )
                self.send(out_port, flooded_packet)

    def handle_new_link(self, port, endpoint, cost):
        """Handle new link."""
        # TODO
        #   update local data structures and forwarding table
        #   broadcast the new link state of this router to all neighbors
        self.neighbors[port] = (endpoint, cost)
        self.link_state_db[self.addr]["links"][endpoint] = cost
        self.forwarding_table[endpoint] = port
        self._recompute_routes()
        self._broadcast_link_state()
        self._sync_link_state(port, endpoint)

    def handle_remove_link(self, port):
        """Handle removed link."""
        # TODO
        #   update local data structures and forwarding table
        #   broadcast the new link state of this router to all neighbors
        if port not in self.neighbors:
            return

        endpoint, _ = self.neighbors.pop(port)
        self.link_state_db[self.addr]["links"].pop(endpoint, None)

        self._recompute_routes()
        self._broadcast_link_state()

    def handle_time(self, time_ms):
        """Handle current time."""
        if time_ms - self.last_time >= self.heartbeat_time:
            self.last_time = time_ms
            # TODO
            #   broadcast the link state of this router to all neighbors
            self._broadcast_link_state()

    def _recompute_routes(self):
        """Compute shortest paths using Dijkstra's algorithm."""
        import heapq

        graph = {
            node: state["links"]
            for node, state in self.link_state_db.items()
        }

        direct_ports = {
            endpoint: port
            for port, (endpoint, cost) in self.neighbors.items()
        }

        distances = {self.addr: 0}
        first_ports = {}
        queue = [(0, self.addr)]

        while queue:
            distance, node = heapq.heappop(queue)

            if distance != distances[node]:
                continue

            for neighbor, link_cost in graph.get(node, {}).items():
                if neighbor == self.addr:
                    continue

                if node == self.addr:
                    next_port = direct_ports.get(neighbor)
                    if next_port is None:
                        continue
                else:
                    next_port = first_ports[node]

                new_distance = distance + link_cost

                if new_distance < distances.get(neighbor, float("inf")):
                    distances[neighbor] = new_distance
                    first_ports[neighbor] = next_port
                    heapq.heappush(queue, (new_distance, neighbor))

        self.forwarding_table = first_ports

    def _sync_link_state(self, port, endpoint):
        """Send known remote link states to a new neighbor."""
        import json
        from packet import Packet

        for origin, state in self.link_state_db.items():
            if origin == self.addr:
                continue

            content = json.dumps({
                "origin": origin,
                "seq": state["seq"],
                "links": state["links"].copy()
            })

            packet = Packet(
                Packet.ROUTING,
                self.addr,
                endpoint,
                content
            )
            self.send(port, packet)

    def _broadcast_link_state(self):
        """Broadcast this router's link state to all neighbors."""
        import json
        from packet import Packet

        self.sequence_number += 1
        self.link_state_db[self.addr]["seq"] = self.sequence_number

        content = json.dumps({
            "origin": self.addr,
            "seq": self.sequence_number,
            "links": self.link_state_db[self.addr]["links"].copy()
        })

        for port, (endpoint, cost) in self.neighbors.items():
            packet = Packet(
                Packet.ROUTING,
                self.addr,
                endpoint,
                content
            )
            self.send(port, packet)

